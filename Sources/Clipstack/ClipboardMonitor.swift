import AppKit
import Foundation

/// Polls the general pasteboard.
///
/// NSPasteboard has no change notification, so the only way to observe copies
/// is to watch `changeCount` on a timer. 300 ms is fast enough to feel instant
/// and cheap enough to ignore.
@MainActor
final class ClipboardMonitor {
    private let store: ClipStore
    private var timer: Timer?
    private var lastChangeCount: Int

    /// Set by Paster so our own writes to the pasteboard are not re-captured.
    var suppressedHash: String?

    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    init(store: ClipStore) {
        self.store = store
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer?.tolerance = 0.1
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        capture(from: pasteboard)
    }

    private func capture(from pasteboard: NSPasteboard) {
        guard let types = pasteboard.types else { return }

        // Password managers and transient tooling mark their writes with these
        // types precisely so history apps skip them. Honour that.
        let markers: Set<NSPasteboard.PasteboardType> = [Self.concealed, Self.transient, Self.autoGenerated]
        if !markers.isDisjoint(with: Set(types)) { return }

        let frontmost = NSWorkspace.shared.frontmostApplication
        if let bundleID = frontmost?.bundleIdentifier,
           Preferences.shared.excludedBundleIDs.contains(bundleID) {
            return
        }

        guard var item = Self.makeItem(from: pasteboard, types: types) else { return }

        if let suppressedHash, suppressedHash == item.contentHash {
            self.suppressedHash = nil
            return
        }

        item.appBundleID = frontmost?.bundleIdentifier
        item.appName = frontmost?.localizedName

        if item.kind == .image {
            let data = Self.pngData(from: pasteboard)
            store.insert(item, imageData: data)
        } else {
            store.insert(item)
        }
    }

    // MARK: - Content typing

    /// Order matters: files before images before colors before plain text,
    /// because a single copy usually offers several representations at once.
    static func makeItem(from pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let joined = urls.map(\.path).joined(separator: "\n")
            return ClipItem(kind: .file,
                            contentHash: ClipItem.hash(joined),
                            text: joined,
                            byteSize: joined.utf8.count)
        }

        if types.contains(.tiff) || types.contains(.png) {
            guard let data = pngData(from: pasteboard) else { return nil }
            let rep = NSBitmapImageRep(data: data)
            return ClipItem(kind: .image,
                            contentHash: ClipItem.hash(data),
                            pixelWidth: rep?.pixelsWide,
                            pixelHeight: rep?.pixelsHigh,
                            byteSize: data.count)
        }

        if types.contains(.color), let color = NSColor(from: pasteboard), let hex = color.hexString {
            return ClipItem(kind: .color,
                            contentHash: ClipItem.hash(hex),
                            text: hex,
                            byteSize: hex.utf8.count)
        }

        if let string = pasteboard.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            let kind: ClipKind
            if let hex = NSColor.hexString(parsing: trimmed) {
                return ClipItem(kind: .color,
                                contentHash: ClipItem.hash(hex),
                                text: hex,
                                byteSize: hex.utf8.count)
            } else if isWebLink(trimmed) {
                kind = .link
            } else {
                kind = .text
            }
            return ClipItem(kind: kind,
                            contentHash: ClipItem.hash(string),
                            text: string,
                            byteSize: string.utf8.count)
        }

        return nil
    }

    private static func isWebLink(_ string: String) -> Bool {
        guard !string.contains(" "), string.count < 2048 else { return false }
        guard let url = URL(string: string), let scheme = url.scheme?.lowercased() else { return false }
        return (scheme == "http" || scheme == "https") && url.host != nil
    }

    static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

extension NSColor {
    /// sRGB hex, uppercase, `#RRGGBB`.
    var hexString: String? {
        guard let converted = usingColorSpace(.sRGB) else { return nil }
        let r = Int((converted.redComponent * 255).rounded())
        let g = Int((converted.greenComponent * 255).rounded())
        let b = Int((converted.blueComponent * 255).rounded())
        return String(format: "#%02X%02X%02X", r, g, b)
    }

    /// Recognises `#RGB`, `#RRGGBB` and `#RRGGBBAA` pasted as plain text.
    static func hexString(parsing string: String) -> String? {
        guard string.hasPrefix("#") else { return nil }
        let body = String(string.dropFirst()).uppercased()
        guard [3, 6, 8].contains(body.count),
              body.allSatisfy({ $0.isHexDigit }) else { return nil }
        return "#" + body
    }

    convenience init?(hexString: String) {
        guard let normalised = NSColor.hexString(parsing: hexString) else { return nil }
        var body = String(normalised.dropFirst())
        if body.count == 3 {
            body = body.map { "\($0)\($0)" }.joined()
        }
        if body.count == 8 { body = String(body.prefix(6)) }
        guard let value = UInt32(body, radix: 16) else { return nil }
        self.init(srgbRed: CGFloat((value >> 16) & 0xFF) / 255,
                  green: CGFloat((value >> 8) & 0xFF) / 255,
                  blue: CGFloat(value & 0xFF) / 255,
                  alpha: 1)
    }
}
